// Runs on Vercel at build time (and locally: `node build.js`).
// Writes config.js from the API_BASE_URL environment variable, so changing the
// backend URL is just "update the Vercel env var + redeploy" - no code edit.
const fs = require("fs");

const raw = (process.env.API_BASE_URL || "").trim().replace(/^["']|["']$/g, "");

if (!raw) {
  console.log("API_BASE_URL not set - keeping the existing config.js");
  process.exit(0);
}
if (!/^https?:\/\/[^\s]+$/i.test(raw)) {
  console.error(`API_BASE_URL is not a valid URL: "${raw}" (example: https://student-api.onrender.com)`);
  process.exit(1);
}
const url = raw.replace(/\/+$/, "").replace(/\/api(\/students)?$/i, "");

fs.writeFileSync(
  "config.js",
  `// Generated by build.js from the API_BASE_URL environment variable.\nwindow.APP_CONFIG = {\n  API_BASE_URL: ${JSON.stringify(url)},\n};\n`
);
console.log(`config.js written -> API_BASE_URL = ${url}`);
